import java.util.ArrayList;
import java.util.Collections;

public class p2_IntroMethods
{
    public static void main(String[] args) 
    {
        // creating an ArrayList 
        ArrayList<String> list = new ArrayList<>();  

        // -------------------------------- adding single element
        list.add("monday");
        list.add("tuesday");
        list.add("wednesday");
        
        // -------------------------------------------- adding single element at index
        list.add(1, "October");
        
        
        // ----------------------------------------------------------------- get elements using index
        System.out.println("\nElement at index-0 : " + list.get(0));
        System.out.println("\nElement at index-1 : " + list.get(1));
        System.out.println("\nElement at index-2 : " + list.get(2));
        
        
        // ----------------------------------------------------------------- Iterate using for each loop 
        System.out.println("\nIteration using for each loop");
        for(String val : list)
            System.out.println("value : " + val);



        // ----------------------------------------------------- set element value 
        list.set(1, "Anjali");
        System.out.println("\nSet Anjali at index-1 : " + list);
        
        
        // ------------------------------------------------------------------------ remove element
        System.out.println("\nRemove Tuesday : " + list.remove("tuesday"));

        
        // -------------------------------------------------- Size of list
        System.out.println("\nList Size : " + list.size());


        // ----------------------------------------------------- Sort list
        Collections.sort(list);
        System.out.println("\nSorted list : " + list);

        // -------------------------------------------------------------------------------- check for existence
        System.out.println("\nList contains Anjali? : " + list.contains("Anjali"));


    }
}